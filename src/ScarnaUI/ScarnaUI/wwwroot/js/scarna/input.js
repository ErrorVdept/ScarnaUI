// Общие хелперы для нативных полей ввода.
//
// Blazor сравнивает новый value="..." с тем, что отрисовал ПРОШЛЫЙ раз, а не с тем, что
// сейчас реально лежит в DOM-элементе. Если пользователь набрал "999", а модель после
// ограничения осталась равной прежним 99 — атрибут не изменился, и Blazor не вернёт
// элементу "99": на экране остаётся "999", а в модели 99. Здесь значение возвращается явно.
export function setValue(input, value) {
    if (input && input.value !== value) {
        input.value = value;
    }
}
